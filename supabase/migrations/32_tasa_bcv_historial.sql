-- -----------------------------------------------------------------------------
-- 3. FUNCIÓN SQL DE CONVERSIÓN HISTÓRICA
-- -----------------------------------------------------------------------------
-- Devuelve la tasa vigente en una fecha dada usando `fecha <= p_fecha` para que
-- pagos realizados en fines de semana o feriados arrastren la última tasa publicada.
CREATE OR REPLACE FUNCTION public.obtener_tasa_bcv_por_fecha(
  p_fecha DATE DEFAULT CURRENT_DATE
)
RETURNS TABLE (
  id        BIGINT,
  fecha     DATE,
  tasa      NUMERIC(18, 8),
  fuente    TEXT,
  creado_en TIMESTAMPTZ
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT
    h.id,
    h.fecha,
    h.tasa,
    h.fuente,
    h.creado_en
  FROM public.tasa_bcv_historial h
  WHERE h.fecha <= p_fecha
  ORDER BY h.fecha DESC
  LIMIT 1;
$$;

COMMENT ON FUNCTION public.obtener_tasa_bcv_por_fecha(DATE) IS
  'Obtiene la tasa BCV exacta o inmediatamente anterior (fines de semana/feriados) para convertir pagos de fechas pasadas.';

GRANT EXECUTE ON FUNCTION public.obtener_tasa_bcv_por_fecha(DATE) TO anon, authenticated, service_role;

-- -----------------------------------------------------------------------------
-- 4. EXTENSIONES `pg_cron` Y `pg_net` + PROGRAMACIÓN DEL CRON DIARIO
-- -----------------------------------------------------------------------------
-- Ajuste de Zona Horaria:
-- Hora objetivo: 1:00 PM hora de Venezuela (VET = UTC-4).
-- Como pg_cron ejecuta expresiones en UTC: 13:00 + 4 horas = 17:00 UTC -> '0 17 * * *'.
CREATE EXTENSION IF NOT EXISTS pg_net;
CREATE EXTENSION IF NOT EXISTS pg_cron;

DO $cron_setup$
BEGIN
  -- Si el job ya existe, lo desprogramamos primero para garantizar idempotencia
  IF EXISTS (
    SELECT 1 FROM cron.job WHERE jobname = 'sync-tasa-bcv-daily'
  ) THEN
    PERFORM cron.unschedule('sync-tasa-bcv-daily');
  END IF;

  -- Programar ejecución diaria a las 17:00 UTC (1:00 PM hora de Venezuela)
  -- Nota: La URL apunta al proyecto Supabase configurado y pasa la service_role_key
  -- en el header Authorization (o lee de vault.decrypted_secrets si está configurado).
  PERFORM cron.schedule(
    'sync-tasa-bcv-daily',
    '0 17 * * *',
    $cmd$
    SELECT net.http_post(
      url := COALESCE(
        current_setting('app.settings.supabase_url', true),
        'https://kbmxxcdetvqamvpdmgxu.supabase.co'
      ) || '/functions/v1/sync-tasa-bcv',
      headers := jsonb_build_object(
        'Content-Type', 'application/json',
        'Authorization', 'Bearer ' || COALESCE(
          current_setting('app.settings.service_role_key', true),
          (SELECT decrypted_secret FROM vault.decrypted_secrets WHERE name = 'service_role_key' LIMIT 1),
          ''
        )
      ),
      body := jsonb_build_object(
        'triggered_by', 'pg_cron',
        'scheduled_at_utc', now()
      ),
      timeout_milliseconds := 25000
    ) AS request_id;
    $cmd$
  );
EXCEPTION
  WHEN OTHERS THEN
    RAISE NOTICE 'No se pudo registrar automáticamente el job en pg_cron (%). Verifique permisos de extensión en el dashboard.', SQLERRM;
END;
$cron_setup$;

-- -----------------------------------------------------------------------------
-- 5. OBSERVABILIDAD: FUNCIONES Y VISTAS DE MONITOREO DE CRON Y FALLBACKS
-- -----------------------------------------------------------------------------
-- Función RPC para que el backend o el panel SuperAdmin consulten el estado del
-- cron (`cron.job` y `cron.job_run_details`) sin exponer el schema `cron` directamente.
CREATE OR REPLACE FUNCTION public.obtener_estado_cron_bcv(p_limit INT DEFAULT 15)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_jobs JSONB := '[]'::jsonb;
  v_runs JSONB := '[]'::jsonb;
BEGIN
  -- Consultar definición del job en cron.job
  BEGIN
    SELECT COALESCE(jsonb_agg(to_jsonb(j)), '[]'::jsonb)
    INTO v_jobs
    FROM (
      SELECT jobid, jobname, schedule, active, command
      FROM cron.job
      WHERE jobname = 'sync-tasa-bcv-daily'
    ) j;
  EXCEPTION WHEN OTHERS THEN
    v_jobs := '[]'::jsonb;
  END;

  -- Consultar historial de ejecuciones recientes en cron.job_run_details
  BEGIN
    SELECT COALESCE(jsonb_agg(to_jsonb(r)), '[]'::jsonb)
    INTO v_runs
    FROM (
      SELECT
        d.runid,
        d.jobid,
        d.status,
        d.return_message,
        d.start_time,
        d.end_time
      FROM cron.job_run_details d
      INNER JOIN cron.job j ON j.jobid = d.jobid
      WHERE j.jobname = 'sync-tasa-bcv-daily'
      ORDER BY d.start_time DESC
      LIMIT p_limit
    ) r;
  EXCEPTION WHEN OTHERS THEN
    v_runs := '[]'::jsonb;
  END;

  RETURN jsonb_build_object(
    'jobs', v_jobs,
    'recent_runs', v_runs
  );
END;
$$;

REVOKE ALL ON FUNCTION public.obtener_estado_cron_bcv(INT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.obtener_estado_cron_bcv(INT) TO authenticated, service_role;
