-- 1. TABLA `tasa_bcv_historial`
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.tasa_bcv_historial (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha     DATE NOT NULL UNIQUE,
  tasa      NUMERIC(18, 8) NOT NULL CHECK (tasa > 0),
  fuente    TEXT NOT NULL DEFAULT 'scraping-bcv',
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.tasa_bcv_historial IS
  'Histórico diario de la tasa oficial del BCV (USD) para conversión exacta de pagos pasados.';

COMMENT ON COLUMN public.tasa_bcv_historial.fecha IS
  'Fecha calendario de la tasa (YYYY-MM-DD). Única por día.';

COMMENT ON COLUMN public.tasa_bcv_historial.tasa IS
  'Valor de 1 USD en Bolívares (VES) con precisión de 8 decimales.';

COMMENT ON COLUMN public.tasa_bcv_historial.fuente IS
  'Origen del dato: "scraping-bcv", "fallback-api-railway", "fallback-dolarapi" o "manual".';

-- Índice descendente en `fecha` para optimizar la búsqueda histórica `fecha <= X ORDER BY fecha DESC LIMIT 1`
CREATE INDEX IF NOT EXISTS idx_tasa_bcv_historial_fecha_desc
  ON public.tasa_bcv_historial (fecha DESC);

